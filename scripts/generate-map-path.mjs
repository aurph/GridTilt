// Bakes the continental-US outline used by the daily social card.
//
// Run:  node scripts/generate-map-path.mjs
// Writes server/us-map.ts (committed). Re-run only if the card's map box
// changes size or client/src/data/us-states.geo.json is replaced.
//
// Why bake it: the server renders cards on demand and should not parse an
// 89 KB geojson or run geoPath per request. Baking the path plus the exact
// scale/translate lets the server rebuild the identical projection with
// geoAlbers().scale(S).translate(T), so cluster dots land on the outline.

import { readFileSync, writeFileSync } from "fs";
import { geoAlbers, geoPath, geoArea, geoBounds } from "d3-geo";

const MAP_W = 478;
const MAP_H = 290;
const SKIP = ["Alaska", "Hawaii", "Puerto Rico"];

const geo = JSON.parse(readFileSync("client/src/data/us-states.geo.json", "utf-8"));

// Guard: a ring wound the wrong way reads as "the whole sphere minus this
// state" in d3's spherical math, which silently destroys the projection fit.
// Virginia shipped inverted; geoAlbersUsa's clipping hid it. Rewind and warn.
let rewound = 0;
for (const f of geo.features) {
  const g = f.geometry;
  if (!g) continue;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const poly of polys) {
    if (poly[0] && geoArea({ type: "Polygon", coordinates: [poly[0]] }) > 2 * Math.PI) {
      poly[0].reverse();
      rewound++;
      console.warn(`rewound inverted outer ring: ${f.properties?.name}`);
    }
  }
}

const continental = {
  type: "FeatureCollection",
  features: geo.features.filter((f) => !SKIP.includes(f.properties?.name)),
};

const [[w, s], [e, n]] = geoBounds(continental);
if (w < -126 || e > -66 || s < 23 || n > 50) {
  throw new Error(`continental bounds look wrong: ${JSON.stringify(geoBounds(continental))}`);
}

const projection = geoAlbers().fitSize([MAP_W, MAP_H], continental);

// ── Bake the projection so the server needs no d3 at runtime ───────────────
//
// The server bundle is CJS with every dependency marked external, and d3-geo
// is ESM-only. require()-ing it works on Node 22+ but throws ERR_REQUIRE_ESM
// on older runtimes, and the card render sits inside a try/catch, so a failure
// there would silently post image-less tweets forever. Instead we solve the
// closed-form Albers constants here and ship plain arithmetic.
//
// geoAlbers is conicEqualArea with parallels 29.5/45.5 and rotate([96, 0]):
//   lambda' = lambda + 96deg
//   rho     = sqrt(c - 2n sin(phi)) / n
//   theta   = n * lambda'
//   raw     = [rho sin(theta), rho0 - rho cos(theta)]
//   screen  = [k * rawX + dx, dy - k * rawY]
// n, c and rho0 are analytic; k, dx and dy are solved against d3's own output
// so `center()`'s offset is captured exactly rather than re-derived.
const PARALLEL_0 = (29.5 * Math.PI) / 180;
const PARALLEL_1 = (45.5 * Math.PI) / 180;
const LAMBDA0_DEG = 96;

const sy0 = Math.sin(PARALLEL_0);
const N = (sy0 + Math.sin(PARALLEL_1)) / 2;
const C = 1 + sy0 * (2 * N - sy0);
const RHO0 = Math.sqrt(C) / N;

function rawAlbers(lat, lng) {
  const lambda = ((lng + LAMBDA0_DEG) * Math.PI) / 180;
  const phi = (lat * Math.PI) / 180;
  const rho = Math.sqrt(C - 2 * N * Math.sin(phi)) / N;
  const theta = lambda * N;
  return [rho * Math.sin(theta), RHO0 - rho * Math.cos(theta)];
}

// Solve k, dx, dy from two reference points, then verify against many more.
const refA = [40.7128, -74.006];
const refB = [37.7749, -122.4194];
const [ax, ay] = rawAlbers(...refA);
const [bx, by] = rawAlbers(...refB);
const [AX, AY] = projection([refA[1], refA[0]]);
const [BX, BY] = projection([refB[1], refB[0]]);
const k = (AX - BX) / (ax - bx);
const dx = AX - k * ax;
const dy = AY + k * ay;

let worst = 0;
for (let lat = 25; lat <= 49; lat += 1.5) {
  for (let lng = -124; lng <= -67; lng += 2.5) {
    const [rx, ry] = rawAlbers(lat, lng);
    const mine = [k * rx + dx, dy - k * ry];
    const theirs = projection([lng, lat]);
    worst = Math.max(worst, Math.hypot(mine[0] - theirs[0], mine[1] - theirs[1]));
  }
}
if (worst > 1e-6) throw new Error(`baked projection drifts ${worst}px from d3`);
console.log(`baked projection verified: worst drift ${worst.toExponential(2)}px`);

const scale = projection.scale();
const [tx, ty] = projection.translate();

// One concatenated path, not one per state: satori truncates large inline SVG
// markup, and per-state <path> elements blew that limit and rendered a
// half-drawn map. Keep this a single path.
const d = continental.features.map((f) => geoPath(projection)(f)).filter(Boolean).join(" ");

const out = `// GENERATED by scripts/generate-map-path.mjs. Do not edit by hand.
// Continental US outline for the daily social card, projected with
// geoAlbers().fitSize([${MAP_W}, ${MAP_H}], continentalUS).

export const MAP_W = ${MAP_W};
export const MAP_H = ${MAP_H};

/** geoAlbers scale/translate, kept for reference and for the parity test. */
export const MAP_SCALE = ${scale};
export const MAP_TRANSLATE: [number, number] = [${tx}, ${ty}];

/**
 * Closed-form Albers constants, solved against d3's own output and verified to
 * better than 1e-6 px across the continental US. The server projects cluster
 * coordinates with these instead of importing d3-geo, which is ESM-only and
 * would throw ERR_REQUIRE_ESM from the CJS server bundle on older Node.
 */
export const ALBERS = {
  n: ${N},
  c: ${C},
  rho0: ${RHO0},
  lambda0Deg: ${LAMBDA0_DEG},
  k: ${k},
  dx: ${dx},
  dy: ${dy},
} as const;

/** ${continental.features.length} continental states + DC, one concatenated path. */
export const US_PATH = ${JSON.stringify(d)};
`;

writeFileSync("server/us-map.ts", out);
console.log(`wrote server/us-map.ts  states=${continental.features.length} rewound=${rewound} pathChars=${d.length} scale=${scale.toFixed(2)}`);
